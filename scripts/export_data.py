#!/usr/bin/env python3
"""Export server-loadable test data from docs/design/v0.44 into shared/data.

Generated files (recipes, economy, moves, routes) are derived from the design
snapshot and must not be edited by hand; `--check` fails when they drift.
Hand-authored files (items, world) live in shared/data and cite their sources.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / 'docs/design/v0.44'
OUT = ROOT / 'shared/data'
SCHEMA_VERSION = 1


def load(name):
    return json.loads((DESIGN / name).read_text(encoding='utf-8'))


def header(source):
    return {'schema_version': SCHEMA_VERSION, 'status': 'test', 'generated_from': source,
            'note': 'GENERATED by scripts/export_data.py; edit the source, not this file.'}


def recipes():
    ledger = load('equipment_ledger_v41.json')
    economy = load('economy_v44.json')
    if economy['recipes'] != ledger['items'] or economy['repair_max_loss'] != ledger['repair_max_loss']:
        sys.exit('economy_v44.json recipes diverge from equipment_ledger_v41.json')
    equipment = []
    for item in ledger['items']:
        eq = item['scrap_equivalent']
        equipment.append({
            'id': item['id'], 'name': item['name'], 'profession': item['profession'],
            'manufacture': item['recipe'], 'repair': item['repair_recipe'],
            'salvage': item['salvage'], 'max_durability': item['max_durability'],
            'main_material': item['main_material'], 'scrap': item['scrap'],
            'scrap_equivalent': [eq['numerator'], eq['denominator']],
        })
    return {**header('docs/design/v0.44/equipment_ledger_v41.json'),
            'repair_max_loss': ledger['repair_max_loss'], 'equipment': equipment}


def economy():
    e = load('economy_v44.json')
    return {**header('docs/design/v0.44/economy_v44.json'),
            'currency': {'unit': 'smallest integer coin'},
            'npc_material_prices': e['prices'], 'npc_order_rewards': e['rewards'],
            'pool': {'initial': e['pool_initial'], 'cap': e['pool_cap'], 'hourly_refill': e['hourly_refill']},
            'account_rolling_limit': {'amount': e['account_limit'], 'window_hours': 24},
            'node_slots_per_account': 200}


def moves():
    text = (DESIGN / '剑拳内功轻功_招式样表_v0.35.md').read_text(encoding='utf-8')
    blocks = re.findall(r'```json\n(.*?)\n```', text, re.S)
    if len(blocks) != 1:
        sys.exit('expected exactly one json block in move table')
    data = json.loads(blocks[0])
    return {**header('docs/design/v0.44/剑拳内功轻功_招式样表_v0.35.md#附'),
            'units': {'time': 'seconds', 'distance': 'meters'},
            'geometry': 'pending M4: range/arc/rectangle from the markdown tables',
            'initial': data['initial'], 'skills': data['skills']}


def routes():
    r = load('transmission_routes_v39.json')
    return {**header('docs/design/v0.44/transmission_routes_v39.json'),
            'nodes': r['nodes'], 'guest_entries': r['guest_entries'],
            'cross_permissions': r['cross_permissions']}


GENERATED = {'recipes.json': recipes, 'economy.json': economy, 'moves.json': moves, 'routes.json': routes}


def render(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=True) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true', help='fail if shared/data differs from a fresh export')
    args = p.parse_args()
    drift = []
    for name, build in GENERATED.items():
        want = render(build())
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != want:
                drift.append(name)
        else:
            path.write_text(want, encoding='utf-8')
    if drift:
        sys.exit('shared/data out of date, run scripts/export_data.py: ' + ', '.join(drift))
    print(('DATA_EXPORT_CHECK_PASS ' if args.check else 'DATA_EXPORT_WROTE ') + str(len(GENERATED)) + ' files')


if __name__ == '__main__':
    main()
